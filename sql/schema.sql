USE jobscraper;

DROP TABLE IF EXISTS ScrapeRun;
DROP TABLE IF EXISTS Job;
DROP TABLE IF EXISTS Company;

CREATE TABLE Company (
	Id INT IDENTITY(1,1),
	Name NVARCHAR(200) NOT NULL,

	CONSTRAINT UQ_Company_Name UNIQUE (Name),
	CONSTRAINT PK_Company PRIMARY KEY (Id)
);
CREATE TABLE Job (
	Id INT IDENTITY(1,1),
	CompanyId INT NOT NULL,
	SourceSite NVARCHAR(50) NOT NULL,
	ExternalId NVARCHAR(50) NOT NULL,
	Title NVARCHAR(300) NOT NULL,
	Location NVARCHAR(200),
	Url NVARCHAR(2048) NOT NULL,
	PostedDate DATE,
	FirstSeen DATETIME2 NOT NULL,
	LastSeen DATETIME2 NOT NULL,
	
	CONSTRAINT PK_Job PRIMARY KEY (Id),
	CONSTRAINT FK_Job_Company FOREIGN KEY (CompanyId) REFERENCES Company(Id),
	CONSTRAINT UQ_Job_Source_ExternalId UNIQUE (SourceSite, ExternalId)
);

CREATE TABLE ScrapeRun (
	Id INT IDENTITY(1,1),
	SourceSite NVARCHAR(50) NOT NULL,
	StartTime DATETIME2 NOT NULL,
	EndTime DATETIME2,
	JobsFound INT NOT NULL,
	JobsNew INT NOT NULL,
	Status VARCHAR(20) NOT NULL,

	CONSTRAINT PK_ScrapeRun PRIMARY KEY (Id)
);